import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from remote_storage import ClassStore, RemoteSession

DATABASE_URL = os.environ.get("DATABASE_URL")
DB_PATH = os.environ.get("SQLITE_PATH", str(Path(__file__).with_name("sinfchat.db")))
CLASS_STORE = ClassStore() if os.getenv("CLASS_STORE_URL") else None
if os.getenv("RENDER") and not (DATABASE_URL or CLASS_STORE):
    raise RuntimeError("SinfChat on Render requires a persistent database")


class Session:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, statement, parameters=()):
        if self.postgres:
            statement = statement.replace("?", "%s")
        return self.connection.execute(statement, parameters)

    def commit(self):
        self.connection.commit()


@contextmanager
def connect():
    if CLASS_STORE:
        session = RemoteSession(CLASS_STORE)
        yield session
        session.commit()
        return
    if DATABASE_URL:
        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    else:
        connection = sqlite3.connect(DB_PATH, timeout=30)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys=ON")
    try:
        with connection:
            yield Session(connection, bool(DATABASE_URL))
    finally:
        connection.close()


def init_schema():
    if CLASS_STORE:
        # Hosted migrations run before the storage service is published.
        CLASS_STORE.batch([["SELECT count(*) FROM users", []]])
        return
    from legacy import SCHEMA
    ident = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if DATABASE_URL else "INTEGER PRIMARY KEY"
    binary = "BYTEA" if DATABASE_URL else "BLOB"
    with connect() as db:
        db.execute(SCHEMA)
        db.execute(f"CREATE TABLE IF NOT EXISTS users(id {ident}, name TEXT UNIQUE NOT NULL, salt TEXT NOT NULL, password TEXT NOT NULL, admin INTEGER DEFAULT 0, banned INTEGER DEFAULT 0)")
        db.execute("CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, uid INTEGER NOT NULL, expiry BIGINT NOT NULL)")
        db.execute(f"CREATE TABLE IF NOT EXISTS messages(id {ident}, sender INTEGER NOT NULL, recipient INTEGER, body TEXT NOT NULL, media_id INTEGER, sent TEXT NOT NULL)")
        db.execute(f"CREATE TABLE IF NOT EXISTS media(id {ident}, owner INTEGER NOT NULL, mime TEXT NOT NULL, data {binary} NOT NULL)")
        db.execute(f"CREATE TABLE IF NOT EXISTS reports(id {ident}, reporter INTEGER, message_id INTEGER, reason TEXT, sent TEXT)")
        db.execute("CREATE INDEX IF NOT EXISTS messages_recipient_id ON messages(recipient,id)")
        db.execute("CREATE INDEX IF NOT EXISTS messages_dm ON messages(sender,recipient,id)")
